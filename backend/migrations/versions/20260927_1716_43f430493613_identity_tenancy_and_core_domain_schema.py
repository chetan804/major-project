def _enum_type_names() -> list[str]:
    """
    Every ENUM type left in the public schema after the tables are dropped.

    Read from the catalogue rather than from the model modules: the type names
    are whatever ``pg_enum`` was asked to create, and duplicating that mapping
    here would be a second place to keep in step. This runs at the end of a
    downgrade, when the only remaining types are the schema's own.
    """
    result = op.get_bind().execute(
        sa.text(
            "SELECT t.typname FROM pg_type t "
            "JOIN pg_namespace n ON n.oid = t.typnamespace "
            "WHERE t.typtype = 'e' AND n.nspname = 'public' "
            "ORDER BY t.typname"
        )
    )
    return [row[0] for row in result]


def _drop_enum_types() -> None:
    for name in _enum_type_names():
        op.execute(sa.text(f'DROP TYPE IF EXISTS "{name}"'))


#: Foreign keys that cannot be created inline with their table, because either the
#: table they reference is created later in this migration's own order, or the
#: reference forms a creation cycle. Each entry is
#: ``(table, column, referenced_table, ondelete)``.
#:
#: Held in one place so ``upgrade`` and ``downgrade`` cannot disagree. A downgrade
#: that forgot to drop one of these fails with "cannot drop table users because
#: other objects depend on it" — a failure this migration has already produced
#: once, which is why the list is data rather than two hand-written blocks.
DEFERRED_FOREIGN_KEYS: tuple[tuple[str, str, str, str], ...] = (
    ("organization_profiles", "tenant_id", "tenants", "CASCADE"),
    ("role_permissions", "role_id", "roles", "CASCADE"),
    ("role_permissions", "permission_id", "permissions", "CASCADE"),
    ("role_permissions", "granted_by", "users", "SET NULL"),
    ("user_roles", "user_id", "users", "CASCADE"),
    ("user_roles", "role_id", "roles", "CASCADE"),
    ("user_roles", "tenant_id", "tenants", "CASCADE"),
    ("sessions", "user_id", "users", "CASCADE"),
    ("audit_logs", "actor_user_id", "users", "SET NULL"),
    ("api_keys", "created_by", "users", "SET NULL"),
    ("api_keys", "rotation_of_id", "api_keys", "SET NULL"),
    ("collection_requests", "fulfilled_by_task_id", "collection_tasks", "SET NULL"),
    ("collection_tasks", "route_stop_id", "route_stops", "SET NULL"),
)


def _foreign_key_name(table: str, column: str, references: str) -> str:
    """The naming-convention name Alembic generates for this constraint."""
    return f"fk_{table}_{column}_{references}"


def _add_deferred_foreign_keys() -> None:
    for table, column, references, ondelete in DEFERRED_FOREIGN_KEYS:
        op.create_foreign_key(
            op.f(_foreign_key_name(table, column, references)),
            table,
            references,
            [column],
            ["id"],
            ondelete=ondelete,
        )


def _drop_deferred_foreign_keys() -> None:
    for table, column, references, _ondelete in DEFERRED_FOREIGN_KEYS:
        op.execute(
            sa.text(
                f"ALTER TABLE {table} DROP CONSTRAINT IF EXISTS "
                f"{_foreign_key_name(table, column, references)}"
            )
        )
